"""MCP server: generated fixes and their pull requests.

    .venv/Scripts/python -m mcp_servers.github

Opening a PR is outward-facing, so the tool is annotated as open-world and enforces the same gates
as the HTTP API: the finding must be confirmed by a human and the fix must be ready. MCP clients
such as Claude Code show the call to the user for approval before it runs.
"""

from __future__ import annotations

from typing import Any

from mcp.server.mcpserver import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from mcp.types import ToolAnnotations
from sqlalchemy import select
from sqlalchemy.orm import Session, sessionmaker

from backend.config import Settings, get_settings
from backend.db.models import Finding, Fix
from backend.fixer.runner import execute_open_pr
from backend.ingest.runner import Publish
from backend.views import fix_dict

from ..common import default_publisher, default_sessions

MAX_DIFF_CHARS = 30_000


def build(
    sessions: sessionmaker[Session] | None = None,
    settings: Settings | None = None,
    publish: Publish | None = None,
    **pr_kwargs: Any,
) -> MCPServer:
    sessions = sessions or default_sessions()
    settings = settings or get_settings()
    publish = publish if publish is not None else default_publisher()
    mcp = MCPServer(
        "codebase-city-github",
        instructions=(
            "Fixes generated by Codebase City's fix agent, and opening their pull requests. Review the diff "
            "and test result with get_fix before calling open_pull_request."
        ),
    )

    @mcp.tool(annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False))
    def list_fixes(finding_id: int) -> list[dict[str, Any]]:
        """Fixes generated for a finding, newest first (status, test result, PR link; no diff)."""
        with sessions() as s:
            return [
                {k: v for k, v in fix_dict(x).items() if k not in ("diff", "test_output")}
                for x in s.scalars(select(Fix).where(Fix.finding_id == finding_id).order_by(Fix.id.desc()))
            ]

    @mcp.tool(annotations=ToolAnnotations(read_only_hint=True, open_world_hint=False))
    def get_fix(fix_id: int) -> dict[str, Any]:
        """A fix's summary, unified diff, files changed, and sandboxed test result."""
        with sessions() as s:
            fix = s.get(Fix, fix_id)
            if fix is None:
                raise ToolError(f"Fix {fix_id} not found.")
            d = fix_dict(fix)
            if len(d["diff"]) > MAX_DIFF_CHARS:
                d["diff"] = d["diff"][:MAX_DIFF_CHARS] + "\n... (diff truncated)"
            d["test_output"] = d["test_output"][-4000:]
            return d

    @mcp.tool(
        annotations=ToolAnnotations(
            read_only_hint=False, destructive_hint=False, idempotent_hint=False, open_world_hint=True
        )
    )
    def open_pull_request(fix_id: int) -> dict[str, Any]:
        """Push the fix to a branch (or a fork) and open a pull request on GitHub. Requires a human-confirmed
        finding and a ready fix. This is visible to the repository's maintainers."""
        if not settings.github_token:
            raise ToolError("GITHUB_TOKEN is not set for this server, so pull requests can't be opened.")
        with sessions() as s:
            fix = s.get(Fix, fix_id)
            if fix is None:
                raise ToolError(f"Fix {fix_id} not found.")
            if fix.status == "pr_opened":
                return {"fix_id": fix_id, "pr_url": fix.pr_url, "already_open": True}
            if fix.status != "ready":
                raise ToolError(f"Fix {fix_id} is {fix.status}, not ready.")
            if s.get(Finding, fix.finding_id).status != "confirmed":
                raise ToolError("The finding must be confirmed by a human before a pull request is opened.")
        url = execute_open_pr(fix_id, settings, sessions, publish, **pr_kwargs)
        if url is None:
            with sessions() as s:
                raise ToolError(s.get(Fix, fix_id).error or "Opening the pull request failed.")
        return {"fix_id": fix_id, "pr_url": url}

    return mcp
